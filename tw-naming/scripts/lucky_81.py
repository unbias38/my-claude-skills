def grade_of(n: int) -> str:
    """Return the grade for stroke total n.

    For n > 81, traditional rule reduces by mod 80 (so 82 → 2, 161 → 1).
    Some schools use n - 80 repeatedly; mod 80 is the most common formula
    but treats 80 itself as a special case (returns 80, not 0).
    """
    if n <= 0:
        return "?"
    if n > 81:
        n = ((n - 1) % 80) + 1
    return LUCKY_81[n][0]


def info_of(n: int) -> tuple[str, str, str]:
    if n > 81:
        n = ((n - 1) % 80) + 1
    return LUCKY_81[n]


