def reference_for(zodiac: str) -> dict:
    """Return {'宜': [(radicals, reason)], '忌': [(radicals, reason)]}."""
    rules = ZODIAC_RADICAL_RULES.get(zodiac, [])
    out: dict[str, list[tuple[str, str]]] = {"宜": [], "忌": []}
    for radicals, direction, reason in rules:
        out[direction].append((radicals, reason))
    return out


def format_reference(zodiac: str) -> str:
    """Pretty-printed multi-line reference for a zodiac."""
    ref = reference_for(zodiac)
    if not ref["宜"] and not ref["忌"]:
        return f"({zodiac}: no rules available)"
    lines = [f"【{zodiac}】字根層級宜忌參考 (來源: zh.wikiversity 生肖姓名學):"]
    lines.append("  宜:")
    for radicals, reason in ref["宜"]:
        lines.append(f"    {radicals:<8}— {reason}")
    lines.append("  忌:")
    for radicals, reason in ref["忌"]:
        lines.append(f"    {radicals:<8}— {reason}")
    return "\n".join(lines)


